#!/usr/bin/env python3
"""Export the HERMAGOTCHI pixel wordmark (same font/styling as the hero banner) as
transparent PNGs + an inline data-URI JS module for the desktop pane header."""
import base64, io
from pathlib import Path
from PIL import Image, ImageDraw
R = Path(__file__).resolve().parents[1]
WHITE=(236,246,240);MINT=(94,234,170);MINT_D=(36,140,110);MINT_DD=(18,70,64);INK=(4,6,14)
BIG={'H':["10001","10001","10001","11111","10001","10001","10001"],'E':["11111","10000","10000","11110","10000","10000","11111"],
'R':["11110","10001","10001","11110","10100","10010","10001"],'M':["10001","11011","10101","10101","10001","10001","10001"],
'A':["01110","10001","10001","11111","10001","10001","10001"],'G':["01111","10000","10000","10111","10001","10001","01111"],
'O':["01110","10001","10001","10001","10001","10001","01110"],'T':["11111","00100","00100","00100","00100","00100","00100"],
'C':["01111","10000","10000","10000","10000","10000","01111"],'I':["11111","00100","00100","00100","00100","00100","11111"]}
def native(s="HERMAGOTCHI"):
    w=len(s)*6-1; m=Image.new("L",(w,7)); d=ImageDraw.Draw(m)
    for i,c in enumerate(s):
        for y,row in enumerate(BIG[c]):
            for x,b in enumerate(row):
                if b=="1": d.point((i*6+x,y),255)
    ol=Image.new("L",(w+2,9))
    for dx in (-1,0,1):
        for dy in (-1,0,1): ol.paste(255,(1+dx,1+dy),m)
    cv=Image.new("RGBA",(w+4,11))
    cv.paste(INK+(255,),(2,2),ol); cv.paste(MINT_DD+(255,),(1,1),ol); cv.paste(INK+(255,),(0,0),ol)
    fill=Image.new("RGBA",m.size); fd=ImageDraw.Draw(fill)
    for y in range(7): fd.line([0,y,w,y],fill=(WHITE if y<3 else MINT if y<5 else MINT_D)+(255,))
    cv.paste(fill,(1,1),m); return cv.crop(cv.getbbox())
def main():
    n=native(); out={}
    for name,k in (("wordmark",3),("wordmark@2x",6)):
        im=n.resize((n.width*k,n.height*k),Image.NEAREST); p=R/"assets"/"ui"/f"{name}.png"; im.save(p,optimize=True)
        b=io.BytesIO(); im.save(b,"PNG",optimize=True); out[name]=(base64.b64encode(b.getvalue()).decode(),im.size)
    (w,h)=out["wordmark"][1]
    (R/"desktop/src/ui/wordmark.js").write_text(
      "// Generated by scripts/make_wordmark.py — do not edit by hand.\n"
      f"export const WORDMARK_WIDTH = {w};\nexport const WORDMARK_HEIGHT = {h};\n"
      f"export const WORDMARK_SRC = \"data:image/png;base64,{out['wordmark'][0]}\";\n"
      f"export const WORDMARK_SRC_2X = \"data:image/png;base64,{out['wordmark@2x'][0]}\";\n")
    print(w,h)
if __name__=="__main__": main()
